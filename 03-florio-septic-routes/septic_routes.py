"""Stochastic routing with a probabilistic duration limit, for septic pump-out trucks.

Applies the vehicle routing problem with stochastic demands, optimal restocking and
probabilistic duration constraints (Florio, Hartl, Minner & Salazar-Gonzalez, Transportation
Science 55(1), 2021; a chapter of A. M. Florio's thesis "Models and Solution Methods for
Stochastic Vehicle Routing Problems", EURO Doctoral Dissertation Award 2021) to a setting the
authors did not study: septic-tank pump-out trucks in Cherokee County, Georgia.

The mapping is one-to-one:
  * "demand" = gallons pumped at a house; unknown until the lid is open (tank size, a second
    tank, rinse water);
  * "capacity" = the truck's tank (3,000 gal);
  * "restocking at the depot" = driving back to the yard to unload at the disposal site;
  * "route duration" = the technician's day, which must end within the 10-hour shift with
    probability >= 95%.

Method (simplified from the paper, stated in README.md):
  * route cost = expected driving + unloading minutes under the OPTIMAL restocking policy,
    computed exactly with the Yee & Golden (1980) stochastic dynamic program, as in the paper;
  * duration feasibility = exact distribution of the day's length under that policy, computed
    by a forward pass over (remaining capacity, elapsed minutes), with Cantelli (one-sided
    Chebyshev) bounds as a fast screen. The paper offers Chebyshev bounds, Monte Carlo with
    inference, or the analytical distribution; I use the bounds + the exact distribution;
  * routes are generated by column generation with a HEURISTIC pricing (best-insertion
    greedy from every seed customer) instead of the paper's exact labeling; the final plan is
    the best set-partitioning over all generated routes (HiGHS MIP). So this is price-and-
    branch, a heuristic, not the paper's exact branch-and-price.
  * extension not in the paper: random lid-locating/digging time per job (independent of the
    volume), so the day's length is random even without extra unloading trips.

Baselines a dispatcher would actually use:
  * AVERAGE-DAY plan: plan with every house at its expected volume and expected service
    time (planned unloads placed optimally), require the planned day to fit in 600 min;
    the driver then pumps until the truck is full ("detour to depot").
  * PADDED plan: the same, but the planned day must fit in 85% of the shift (510 min),
    the usual rule of thumb.
Every plan is evaluated exactly under the same stochastic model, and checked by Monte Carlo.

Usage: uv run --with numpy --with scipy python septic_routes.py  -> results.json
"""

