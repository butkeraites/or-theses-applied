# ---------------------------------------------------------------- parameters
UNIT = 50  # gallons per volume unit
Q = 60  # truck tank: 3,000 gallons
SHIFT = 600  # minutes, yard to yard (10 hours)
PAD = 0.85  # rule-of-thumb buffer for the padded plan
ALPHA = 0.05  # duration limit must hold with probability >= 1 - ALPHA
DUMP = 20  # minutes to unload at the yard / disposal site, each time
SETUP = 25  # minutes per job: hoses, paperwork, closing up
PUMP_GPM = 100  # gallons per minute pumped
DIG = {0: 0.5, 15: 0.3, 45: 0.2}  # minutes to locate/dig up the lid (synthetic)
SPEED_KMH = 45.0
DETOUR = 1.3  # road distance / straight-line distance (stated assumption)
N_JOBS = 24  # pump-outs per day
N_DAYS = 16
SEED = 2026
YARD = (34.2368, -84.4908)  # Canton, GA (hypothetical yard + disposal site)
BBOX = (34.10, 34.36, -84.65, -84.32)  # lat_min, lat_max, lon_min, lon_max (Cherokee Co.)
TMAX = 1100  # minutes tracked in the duration distribution
MC_SAMPLES = 4000  # Monte Carlo days per plan per instance (validation)
TRUCK_FIX = 600  # planning cost of using one more truck-day, in minutes (not in the paper)

# ACS 2024 1-year, table B25041 (bedrooms), Cherokee County, GA (05000US13057),
# retrieved via the Census Reporter API. Housing units by bedrooms.
ACS_BEDROOMS = {0: 1621, 1: 3966, 2: 14414, 3: 44055, 4: 29613, 5: 17712}  # 5 = "5 or more"

# Georgia rule 511-3-1-.05(3): 1,000 gal for 1-4 bedrooms, +250 gal per bedroom over four.
# "5 or more" is treated as 5. The rest of the volume model is synthetic:
EXTRA_TANK = {0: 0.55, 250: 0.30, 500: 0.15}  # installed above code minimum
RINSE = {0: 0.5, 100: 0.3, 200: 0.2}  # water used to break up the scum layer
SECOND_TANK = (0.08, 1000)  # prob., gallons: a second tank or an oversized old system


def code_min(bedrooms: int) -> int:
    return 1000 + 250 * max(0, bedrooms - 4)


def convolve(a: dict, b: dict) -> dict:
    out: dict = {}
    for x, p in a.items():
        for y, r in b.items():
            out[x + y] = out.get(x + y, 0.0) + p * r
    return out


def volume_pmf(bedrooms: int) -> np.ndarray:
    base = {code_min(bedrooms) + e: p for e, p in EXTRA_TANK.items()}
    g = convolve(base, RINSE)
    g = convolve(g, {0: 1 - SECOND_TANK[0], SECOND_TANK[1]: SECOND_TANK[0]})
    pmf = np.zeros(Q + 1)
    for gal, p in g.items():
        pmf[math.ceil(gal / UNIT)] += p  # rounded up to whole 50-gal units
    return pmf


def haversine_km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * 6371.0 * math.asin(math.sqrt(h))


# ---------------------------------------------------------------- instance
class Day:
    def __init__(self, rng: np.random.Generator, idx: int):
        self.idx = idx
        beds = np.array(list(ACS_BEDROOMS.keys()))
        w = np.array(list(ACS_BEDROOMS.values()), float)
        self.bedrooms = rng.choice(beds, size=N_JOBS, p=w / w.sum())
        lat = rng.uniform(BBOX[0], BBOX[1], N_JOBS)
        lon = rng.uniform(BBOX[2], BBOX[3], N_JOBS)
        self.pts = [YARD] + list(zip(lat.tolist(), lon.tolist()))
        n = N_JOBS + 1
        self.t = np.zeros((n, n), dtype=int)  # driving minutes, node 0 = yard
        for i in range(n):
            for j in range(n):
                if i != j:
                    km = haversine_km(self.pts[i], self.pts[j]) * DETOUR
                    self.t[i, j] = max(1, round(km / SPEED_KMH * 60))
        self.pmf = [None] + [volume_pmf(int(b)) for b in self.bedrooms]
        self.mean_units = [0.0] + [float(np.dot(np.arange(Q + 1), p)) for p in self.pmf[1:]]
        self.build_transitions()

    def build_transitions(self):
        """Per customer j: M[q, q'] = P(next remaining = q' | arrive with q), plus failure
        counts F[q] = E[number of extra unload trips at j | q] (the paper's Psi)."""
        self.M, self.F, self.kvals = [None], [None], [None]
        qs = np.arange(Q + 1)
        for j in range(1, N_JOBS + 1):
            p = self.pmf[j]
            M = np.zeros((Q + 1, Q + 1))
            F = np.zeros(Q + 1)
            ks = [k for k in range(Q + 1) if p[k] > 0]
            for k in ks:
                psi = np.maximum(0, np.ceil((k - qs) / Q)).astype(int)
                qn = Q * psi + qs - k
                M[qs, qn] += p[k]
                F += p[k] * psi
            self.M.append(M)
            self.F.append(F)
            self.kvals.append(ks)


# ---------------------------------------------------------------- route evaluation
def det_cost_duration(day: Day, route, tlim):
    """Average-day planning view: every house at its expected volume and expected
    service time. Planned unloads are placed optimally (a DP over remaining capacity).
    Returns (planned cost, planned duration) or None if infeasible."""
    vols = [round(day.mean_units[j]) for j in route]
    mean_dig = sum(k * p for k, p in DIG.items())
    # DP over position with deterministic volumes: state = remaining capacity
    INF = 10**9
    nodes = [0] + list(route)
    best = {Q: 0.0}  # remaining capacity -> cost so far (at yard, empty)
    for idx, j in enumerate(route):
        prev = nodes[idx]
        nxt: dict = {}
        for q, c in best.items():
            for restock in (False, True):
                if restock:
                    cc, qq = c + day.t[prev, 0] + DUMP + day.t[0, j], Q
                else:
                    cc, qq = c + day.t[prev, j], q
                v = vols[idx]
                psi = max(0, math.ceil((v - qq) / Q))
                cc += psi * (2 * day.t[j, 0] + DUMP)
                qn = Q * psi + qq - v
                if cc < nxt.get(qn, INF):
                    nxt[qn] = cc
        best = nxt
    cost = min(c + day.t[route[-1], 0] + DUMP for c in best.values())
    service = sum(SETUP + vols[i] * UNIT / PUMP_GPM + mean_dig for i in range(len(route)))
    dur = cost + service
    return (cost, dur) if dur <= tlim else None


def stoch_policy(day: Day, route, optimal=True):
    """Yee & Golden DP (as in Florio et al.): nu[i][q] expected remaining cost after
    serving the i-th customer with q units left; returns (expected cost, decisions) where
    decisions[i][q] = True means 'unload before going to the next customer'."""
    l = len(route)
    nu = np.full(Q + 1, day.t[route[-1], 0] + DUMP, dtype=float)
    restock = [None] * l
    for i in range(l - 2, -1, -1):
        a, b = route[i], route[i + 1]
        fail = (2 * day.t[b, 0] + DUMP) * day.F[b]
        cont = day.M[b] @ nu
        direct = day.t[a, b] + fail + cont
        rep = day.t[a, 0] + DUMP + day.t[0, b] + fail[Q] + cont[Q]
        if optimal:
            dec = rep < direct - 1e-9
            nu = np.where(dec, rep, direct)
        else:
            dec = np.zeros(Q + 1, bool)
            nu = direct
        restock[i] = dec
    b = route[0]
    fail = (2 * day.t[b, 0] + DUMP) * day.F[b]
    cost = day.t[0, b] + fail[Q] + (day.M[b] @ nu)[Q]
    return float(cost), restock


def dig_pmf_n(n: int) -> np.ndarray:
    base = np.zeros(max(DIG) + 1)
    for k, p in DIG.items():
        base[k] = p
    out = np.array([1.0])
    for _ in range(n):
        out = np.convolve(out, base)
    return out


DIG_N = {n: dig_pmf_n(n) for n in range(0, 16)}


def duration_dist(day: Day, route, restock) -> np.ndarray:
    """Exact pmf of the day's length (minutes) under the given restocking decisions.
    Forward pass over (remaining capacity q, elapsed minutes t); dig times are independent
    of everything else, so their total is convolved once at the end."""
    P = np.zeros((Q + 1, TMAX))
    P[Q, 0] = 1.0
    prev = 0
    for i, j in enumerate(route):
        if i > 0 and restock[i - 1] is not None:
            dec = restock[i - 1]
            Pn = np.zeros_like(P)
            go = day.t[prev, j]
            rs = day.t[prev, 0] + DUMP + day.t[0, j]
            mass_rs = P[dec].sum(axis=0)
            Pn[~dec, go:] = P[~dec, : TMAX - go]
            Pn[Q, rs:] += mass_rs[: TMAX - rs]
            P = Pn
        else:
            P = np.concatenate([np.zeros((Q + 1, day.t[prev, j])), P[:, : TMAX - day.t[prev, j]]], axis=1)
        # serve customer j
        Pn = np.zeros_like(P)
        p = day.pmf[j]
        fail_rt = 2 * day.t[j, 0] + DUMP
        for k in day.kvals[j]:
            pump = round(SETUP + k * UNIT / PUMP_GPM)
            for q in range(Q + 1):
                row = P[q]
                if not row.any():
                    continue
                psi = max(0, math.ceil((k - q) / Q))
                qn = Q * psi + q - k
                s = pump + psi * fail_rt
                Pn[qn, s:] += p[k] * row[: TMAX - s]
        P = Pn
        prev = j
    back = day.t[prev, 0] + DUMP
    dist = P.sum(axis=0)
    dist = np.concatenate([np.zeros(back), dist[: TMAX - back]])
    dist = np.convolve(dist, DIG_N[len(route)])[:TMAX]
    return dist


def duration_moments(day: Day, route, restock):
    """Mean and variance of the day's length (for the Cantelli screen)."""
    m0 = np.zeros(Q + 1)
    m1 = np.zeros(Q + 1)
    m2 = np.zeros(Q + 1)
    m0[Q] = 1.0
    prev = 0
    qs = np.arange(Q + 1)

    def shift(a0, a1, a2, s):
        return a0, a1 + s * a0, a2 + 2 * s * a1 + s * s * a0

    for i, j in enumerate(route):
        if i > 0:
            dec = restock[i - 1]
            go = day.t[prev, j]
            rs = day.t[prev, 0] + DUMP + day.t[0, j]
            a0, a1, a2 = shift(m0 * ~dec, m1 * ~dec, m2 * ~dec, go)
            b0, b1, b2 = shift((m0 * dec).sum(), (m1 * dec).sum(), (m2 * dec).sum(), rs)
            a0[Q] += b0
            a1[Q] += b1
            a2[Q] += b2
            m0, m1, m2 = a0, a1, a2
        else:
            m0, m1, m2 = shift(m0, m1, m2, day.t[0, j])
        n0, n1, n2 = np.zeros(Q + 1), np.zeros(Q + 1), np.zeros(Q + 1)
        fail_rt = 2 * day.t[j, 0] + DUMP
        for k in day.kvals[j]:
            pk = day.pmf[j][k]
            psi = np.maximum(0, np.ceil((k - qs) / Q)).astype(int)
            qn = Q * psi + qs - k
            s = round(SETUP + k * UNIT / PUMP_GPM) + psi * fail_rt
            a0, a1, a2 = m0 * pk, (m1 + s * m0) * pk, (m2 + 2 * s * m1 + s * s * m0) * pk
            np.add.at(n0, qn, a0)
            np.add.at(n1, qn, a1)
            np.add.at(n2, qn, a2)
        m0, m1, m2 = n0, n1, n2
        prev = j
    back = day.t[prev, 0] + DUMP
    M0, M1, M2 = m0.sum(), m1.sum(), m2.sum()
    mu = M1 + back * M0
    ex2 = M2 + 2 * back * M1 + back * back * M0
    dmu = sum(k * p for k, p in DIG.items())
    dvar = sum(k * k * p for k, p in DIG.items()) - dmu**2
    n = len(route)
    return mu + n * dmu, ex2 - mu * mu + n * dvar


STATS = {"exact_checks": 0, "cantelli_accept": 0, "cantelli_reject": 0}


def chance_feasible(day: Day, route, restock, alpha=ALPHA):
    mu, var = duration_moments(day, route, restock)
    var = max(var, 1e-9)
    if mu <= SHIFT:
        a = SHIFT - mu
        if var / (var + a * a) <= alpha:  # Cantelli upper bound on P(D > L)
            STATS["cantelli_accept"] += 1
            return True
    else:
        a = mu - SHIFT
        if var / (var + a * a) < 1 - alpha:  # Cantelli upper bound on P(D <= L)
            STATS["cantelli_reject"] += 1
            return False
    STATS["exact_checks"] += 1
    dist = duration_dist(day, route, restock)
    return dist[SHIFT + 1 :].sum() <= alpha


# ---------------------------------------------------------------- planners
class Evaluator:
    """kind: 'thesis' (optimal restocking + P(D<=L) >= 95%), 'meanonly' (optimal restocking,
    expected day <= L), 'avg' (average-day plan, planned day <= L), 'pad' (<= 0.85 L)."""

    def __init__(self, day: Day, kind: str, alpha=ALPHA):
        self.day, self.kind, self.alpha = day, kind, alpha
        self.cache: dict = {}

    def cost(self, route):
        key = tuple(route)
        if key in self.cache:
            return self.cache[key]
        d = self.day
        if self.kind in ("avg", "pad"):
            r = det_cost_duration(d, route, SHIFT if self.kind == "avg" else PAD * SHIFT)
            out = None if r is None else r[0] + TRUCK_FIX
        else:
            c, dec = stoch_policy(d, route, optimal=True)
            if self.kind == "thesis":
                ok = chance_feasible(d, route, dec, self.alpha)
            else:
                ok = duration_moments(d, route, dec)[0] <= SHIFT
            out = c + TRUCK_FIX if ok else None
        self.cache[key] = out
        return out

    def quick_cost(self, route):
        """Cost without the feasibility check (used to rank insertions)."""
        if self.kind in ("avg", "pad"):
            r = det_cost_duration(self.day, route, 10**9)
            return r[0] + TRUCK_FIX
        return stoch_policy(self.day, route, optimal=True)[0] + TRUCK_FIX


def solve_lp(pool, costs, n, K=None):
    A = np.zeros((n + (K is not None), len(pool)))
    for c, r in enumerate(pool):
        for j in r:
            A[j - 1, c] = 1
    b = np.ones(n)
    if K is not None:
        A[n, :] = 1
        b = np.append(b, K)
    res = linprog(costs, A_eq=A, b_eq=b, bounds=(0, None), method="highs")
    if res.status != 0:
        return None, None, A, b
    duals = res.eqlin.marginals
    mu = duals[n] if K is not None else 0.0
    return res.fun, (duals[:n], mu), A, b


def price(ev: Evaluator, duals_mu, nn, max_new=60):
    """Heuristic pricing: grow a route from every seed by best insertion of reduced cost."""
    n = N_JOBS
    duals, mu = duals_mu
    new = {}
    for s in range(1, n + 1):
        route = [s]
        rc = ev.cost(route) - duals[s - 1] - mu
        while True:
            cand = set()
            for v in route:
                cand.update(nn[v][:6])
            cand -= set(route)
            moves = []
            for c in cand:
                for pos in range(len(route) + 1):
                    r2 = route[:pos] + [c] + route[pos:]
                    qc = ev.quick_cost(r2)
                    rc2 = qc - sum(duals[j - 1] for j in r2) - mu
                    if rc2 < rc - 1e-6:
                        moves.append((rc2, r2))
            moves.sort(key=lambda m: m[0])
            moved = False
            for rc2, r2 in moves[:4]:
                if ev.cost(r2) is not None:
                    route, rc, moved = r2, rc2, True
                    break
            if not moved:
                break
            if rc < -1e-6:
                new[tuple(route)] = rc
        if rc < -1e-6:
            new[tuple(route)] = rc
    best = sorted(new.items(), key=lambda kv: kv[1])[:max_new]
    return [list(r) for r, _ in best]


def plan(day: Day, kind: str, max_iter=60, K=None, alpha=ALPHA, seed_routes=()):
    ev = Evaluator(day, kind, alpha)
    n = N_JOBS
    nn = {v: [int(u) for u in np.argsort(day.t[v, 1:]) + 1 if u + 1 != v] for v in range(1, n + 1)}
    pool = [[j] for j in range(1, n + 1)]
    # seed with sweep routes so the LP starts reasonable
    ang = [math.atan2(day.pts[j][0] - YARD[0], day.pts[j][1] - YARD[1]) for j in range(1, n + 1)]
    order = [int(i) + 1 for i in np.argsort(ang)]
    for start in range(n):
        rot = order[start:] + order[:start]
        r: list = []
        for j in rot:
            if ev.cost(r + [j]) is not None:
                r = r + [j]
            else:
                if r:
                    pool.append(r)
                r = [j]
        if r:
            pool.append(r)
    pool += [list(r) for r in seed_routes if ev.cost(list(r)) is not None]
    seen = {tuple(r) for r in pool}
    pool = [list(r) for r in seen]
    costs = [ev.cost(r) for r in pool]
    it = 0
    for it in range(max_iter):
        lp, duals, _, _ = solve_lp(pool, costs, n, K)
        if lp is None:  # K-route LP infeasible with the current pool: price on covering only
            lp, duals, _, _ = solve_lp(pool, costs, n)
        cols = price(ev, duals, nn)
        cols = [c for c in cols if tuple(c) not in seen]
        if not cols:
            break
        for c in cols:
            seen.add(tuple(c))
            pool.append(c)
            costs.append(ev.cost(c))
    lp, _, A, b = solve_lp(pool, costs, n, K)
    res = milp(
        c=np.array(costs),
        constraints=LinearConstraint(A, b, b),
        integrality=np.ones(len(pool)),
        bounds=(0, 1),
        options={"time_limit": 120},
    )
    if res.x is None:
        raise RuntimeError(f"MIP failed: {kind} K={K} {res.message}")
    chosen = [pool[i] for i in range(len(pool)) if res.x[i] > 0.5]
    return chosen, {"lp": lp, "ip": float(res.fun), "pool": len(pool), "cg_iters": it + 1}


# ---------------------------------------------------------------- evaluation
def evaluate(day: Day, routes, optimal: bool):
    """Exact expected cost and day-length distribution of each route under a policy."""
    out = []
    for r in routes:
        c, dec = stoch_policy(day, r, optimal=optimal)
        dist = duration_dist(day, r, dec)
        ts = np.arange(TMAX)
        p_over = float(dist[SHIFT + 1 :].sum())
        e_over = float(((ts - SHIFT).clip(0) * dist).sum())
        e_dur = float((ts * dist).sum())
        p_late60 = float(dist[SHIFT + 61 :].sum())
        out.append(
            {
                "route": r,
                "cost": c,
                "p_over": p_over,
                "e_over": e_over,
                "e_dur": e_dur,
                "p_over60": p_late60,
                "exp_gal": float(sum(day.mean_units[j] for j in r) * UNIT),
                "q95": int(np.searchsorted(np.cumsum(dist), 0.95)),
            }
        )
    return out


def simulate(day: Day, routes, optimal: bool, rng, samples=MC_SAMPLES):
    """Monte Carlo check of the exact numbers: sample volumes and dig times, drive the
    policy, return per-route overtime indicators and day lengths."""
    res = []
    digk = np.array(list(DIG.keys()))
    digp = np.array(list(DIG.values()))
    for r in routes:
        _, dec = stoch_policy(day, r, optimal=optimal)
        D = np.zeros(samples)
        q = np.full(samples, Q)
        prev = 0
        for i, j in enumerate(r):
            if i > 0:
                rs = dec[i - 1][q]
                D += np.where(rs, day.t[prev, 0] + DUMP + day.t[0, j], day.t[prev, j])
                q = np.where(rs, Q, q)
            else:
                D += day.t[0, j]
            k = rng.choice(Q + 1, size=samples, p=day.pmf[j])
            psi = np.maximum(0, np.ceil((k - q) / Q)).astype(int)
            D += np.round(SETUP + k * UNIT / PUMP_GPM) + psi * (2 * day.t[j, 0] + DUMP)
            D += rng.choice(digk, size=samples, p=digp)
            q = Q * psi + q - k
            prev = j
        D += day.t[prev, 0] + DUMP
        res.append(D)
    return np.array(res)  # routes x samples


def summarize(evals, sims):
    over_any = (sims > SHIFT).any(axis=0).mean() if len(sims) else 0.0
    p_none = float(np.prod([1 - e["p_over"] for e in evals]))
    return {
        "trucks": len(evals),
        "jobs_per_truck": N_JOBS / len(evals),
        "exp_drive_unload_min": sum(e["cost"] for e in evals),
        "exp_overtime_min": sum(e["e_over"] for e in evals),
        "p_any_truck_over": 1 - p_none,
        "mean_p_route_over": float(np.mean([e["p_over"] for e in evals])),
        "max_p_route_over": float(np.max([e["p_over"] for e in evals])),
        "routes_over_alpha": int(sum(e["p_over"] > ALPHA + 1e-9 for e in evals)),
        "p_route_over60_mean": float(np.mean([e["p_over60"] for e in evals])),
        "exp_day_min_mean": float(np.mean([e["e_dur"] for e in evals])),
        "exp_load_factor_mean": float(np.mean([e["exp_gal"] / (Q * UNIT) for e in evals])),
        "mc_p_any_truck_over": float(over_any),
        "mc_mean_p_route_over": float((sims > SHIFT).mean(axis=1).mean()),
        "mc_exp_overtime_min": float((sims - SHIFT).clip(0).mean(axis=1).sum()),
    }


def main():
    t0 = time.time()
    rng = np.random.default_rng(SEED)
    mc_rng = np.random.default_rng(SEED + 1)
    days = [Day(rng, d) for d in range(N_DAYS)]
    # (plan kind, execution policy) pairs reported
    combos = [
        ("avg", False, "Average-day plan, pump until full"),
        ("avg", True, "Average-day plan, optimal unloading"),
        ("pad", False, "Padded plan (85% of shift), pump until full"),
        ("pad", True, "Padded plan (85% of shift), optimal unloading"),
        ("meanonly", True, "Optimal unloading, expected day <= shift (no chance limit)"),
        ("thesis", True, "Thesis: optimal unloading + P(day <= shift) >= 95%"),
        ("thesis", False, "Thesis routes, pump until full"),
        ("avgK", False, "Average-day plan with the thesis's truck count, pump until full"),
        ("avgK", True, "Average-day plan with the thesis's truck count, optimal unloading"),
        ("thesis90", True, "Thesis method at 90%"),
        ("thesis98", True, "Thesis method at 98%"),
    ]
    per_day = []
    for day in days:
        rec = {"day": day.idx, "plans": {}}
        plans = {}
        for kind in ("avg", "pad", "meanonly", "thesis", "avgK", "thesis90", "thesis98"):
            ts = time.time()
            if kind == "avgK":
                th = plans["thesis"][0]
                routes, info = plan(day, "avg", K=len(th), seed_routes=th)
            elif kind.startswith("thesis") and kind != "thesis":
                routes, info = plan(day, "thesis", alpha=0.10 if kind == "thesis90" else 0.02)
            else:
                routes, info = plan(day, kind)
            info["seconds"] = round(time.time() - ts, 1)
            plans[kind] = (routes, info)
        for kind, optimal, label in combos:
            routes, info = plans[kind]
            ev = evaluate(day, routes, optimal)
            sims = simulate(day, routes, optimal, mc_rng)
            s = summarize(ev, sims)
            s.update({"label": label, "solve": info})
            if day.idx == 0:
                s["routes"] = ev
            rec["plans"][f"{kind}|{'opt' if optimal else 'dtd'}"] = s
        per_day.append(rec)
        th = rec["plans"]["thesis|opt"]
        av = rec["plans"]["avg|dtd"]
        print(
            f"day {day.idx:2d}: avg {av['trucks']} trucks P(any OT)={av['p_any_truck_over']:.2f} "
            f"cost={av['exp_drive_unload_min']:.0f} | thesis {th['trucks']} trucks "
            f"P(any OT)={th['p_any_truck_over']:.2f} cost={th['exp_drive_unload_min']:.0f} "
            f"[{time.time() - t0:.0f}s]",
            flush=True,
        )

    keys = list(per_day[0]["plans"].keys())
    agg = {}
    for k in keys:
        rows = [d["plans"][k] for d in per_day]
        num = [m for m, v in rows[0].items() if isinstance(v, (int, float))]
        agg[k] = {"label": rows[0]["label"]}
        for m in num:
            vals = [r[m] for r in rows]
            agg[k][m] = float(np.mean(vals))
        agg[k]["trucks_total"] = int(sum(r["trucks"] for r in rows))
        agg[k]["routes_over_alpha_total"] = int(sum(r["routes_over_alpha"] for r in rows))
        agg[k]["days_trucks"] = [r["trucks"] for r in rows]
        agg[k]["days_p_any_over"] = [round(r["p_any_truck_over"], 4) for r in rows]
        agg[k]["days_cost"] = [round(r["exp_drive_unload_min"], 1) for r in rows]
        agg[k]["days_overtime"] = [round(r["exp_overtime_min"], 1) for r in rows]
        agg[k]["mean_lp_ip_gap_pct"] = float(
            np.mean([100 * (r["solve"]["ip"] - r["solve"]["lp"]) / r["solve"]["lp"] for r in rows])
        )
        agg[k]["mean_solve_seconds"] = float(np.mean([r["solve"]["seconds"] for r in rows]))

    # instance description (day 0) for the figures
    d0 = days[0]
    vol_example = {b: volume_pmf(b).tolist() for b in (3, 5)}
    out = {
        "params": {
            "unit_gal": UNIT,
            "truck_gal": Q * UNIT,
            "shift_min": SHIFT,
            "pad": PAD,
            "alpha": ALPHA,
            "dump_min": DUMP,
            "setup_min": SETUP,
            "pump_gpm": PUMP_GPM,
            "dig": DIG,
            "speed_kmh": SPEED_KMH,
            "detour": DETOUR,
            "jobs_per_day": N_JOBS,
            "days": N_DAYS,
            "seed": SEED,
            "truck_fix_min": TRUCK_FIX,
            "yard": YARD,
            "bbox": BBOX,
            "acs_bedrooms": ACS_BEDROOMS,
            "extra_tank": EXTRA_TANK,
            "rinse": RINSE,
            "second_tank": SECOND_TANK,
            "mc_samples": MC_SAMPLES,
        },
        "volume_pmf_units_by_bedrooms": vol_example,
        "mean_gal_by_bedrooms": {
            b: float(np.dot(np.arange(Q + 1), volume_pmf(b)) * UNIT) for b in range(0, 6)
        },
        "day0": {
            "points": d0.pts,
            "bedrooms": d0.bedrooms.tolist(),
            "mean_gal": [m * UNIT for m in d0.mean_units[1:]],
        },
        "aggregate": agg,
        "per_day": per_day,
        "feasibility_stats": STATS,
        "runtime_s": round(time.time() - t0, 1),
    }
    (HERE / "results.json").write_text(json.dumps(out, indent=1, default=float))
    print(json.dumps({k: {m: v for m, v in a.items() if not isinstance(v, list)} for k, a in agg.items()}, indent=1))
    print("feasibility checks:", STATS, "runtime", out["runtime_s"], "s")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        N_DAYS = int(sys.argv[1])
    main()
